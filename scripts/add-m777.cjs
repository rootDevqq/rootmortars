function toTable(rows) {
  return rows.map(([range, elevation, tof, dElev, wc, wl]) => ({
    range,
    elevation,
    tof,
    dElev: dElev,
    windCross: wc,
    windLong: wl,
  }));
}

function makePt(charge, variant, rows) {
  const angleWord = variant === 'low_angle' ? 'Low' : 'High';
  const ranges = rows.map(r => r[0]);
  return {
    id: `m777_m107_c${charge}_${variant === 'low_angle' ? 'low' : 'high'}`,
    name: `M107 HE Charge ${charge} ${angleWord} Angle`,
    type: 'HE',
    variant,
    charge,
    minRange: Math.min(...ranges),
    maxRange: Math.max(...ranges),
    dispersion: DISP[variant === 'low_angle' ? 'low' : 'high'][charge],
    ballisticTable: toTable(rows),
  };
}

